import express from "express";
import cors from "cors";
import dotenv from "dotenv";
import http from "http";

import authRoutes from "./routes/authRoutes.js";
import { connectDB } from "./config/db.js";

import "./mqtt.js";
import { initWebSocket } from "./websocket.js";


// =========================================================
// DOTENV
// =========================================================

dotenv.config({
    path: "./backend/.env",
});


// =========================================================
// EXPRESS
// =========================================================

const app =
    express();


app.use(
    cors()
);


app.use(
    express.json()
);


// =========================================================
// ROUTES
// =========================================================

app.use(
    "/api/auth",
    authRoutes
);


// =========================================================
// ROOT
// =========================================================

app.get(
    "/",
    (req, res) => {

        res.send(
            "Fleet Backend Running 🚀"
        );

    }
);


// =========================================================
// DATABASE
// =========================================================

connectDB();


// =========================================================
// HTTP SERVER
// =========================================================

const server =
    http.createServer(app);


// =========================================================
// WEBSOCKET
// =========================================================

initWebSocket();


// =========================================================
// PORT
// =========================================================

const PORT =
    process.env.PORT || 5000;


// =========================================================
// START SERVER
// =========================================================

server.listen(
    PORT,
    () => {

        console.log(
            `🚀 Server Running : ${PORT}`
        );

    }
);